const PET_MAP: ReadonlyMap<string, PetDef> = new Map(
  PET_LIST.map((p) => [p.id, p]),
)

/** 按 id 取宠物定义，未知 id 抛错（数据错误应尽早暴露） */
export function getPet(id: string): PetDef {
  const pet = PET_MAP.get(id)
  if (!pet) throw new Error(`未知宠物 id: ${id}`)
  return pet
}

/** 安全查询 */
export function findPet(id: string): PetDef | undefined {
  return PET_MAP.get(id)
}

